export const bookingMessages = (locale: Locale): BookingMessages =>
  locale === "ar" ? ar : locale === "ku" ? ku : en;

export const originLabel = (
  origin: "patientBooked" | "clinicCreated" | "walkIn" | undefined,
  m: BookingMessages,
): string | null =>
  origin === "patientBooked"
    ? m.sourceApp
    : origin === "clinicCreated"
      ? m.sourcePhone
      : origin === "walkIn"
        ? m.sourceWalkIn
        : null;

/**
 * Clock and day formats for the board and booking screens. Arabic and Badini
 * use a 24-hour clock with Western digits (what Duhok clinics write on
 * appointment cards); Badini day names use Kurdish in Arabic script because
 * browsers have no Badini calendar data.
 */
export const clockFormat = (locale: Locale, timeZone: string) => ({
  format: (value: Date | string) => formatter(locale, timeZone).time(value),
});
export const dayFormat = (
  locale: Locale,
  timeZone: string,
  withTime = false,
) => ({
  format: (value: Date | string) => {
    const f = formatter(locale, timeZone);
    return withTime
      ? `${f.weekdayDay(value)}${f.comma}${f.time(value)}`
      : f.weekdayDay(value);
  },
});
