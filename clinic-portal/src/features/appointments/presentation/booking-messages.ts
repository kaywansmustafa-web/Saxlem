export const bookingMessages = (locale: Locale): BookingMessages =>
  locale === "ar" ? ar : locale === "ku" ? ku : en;

export const originLabel = (
  origin: "patientBooked" | "clinicCreated" | "walkIn" | undefined,
  m: BookingMessages,
): string | null =>
  origin === "patientBooked"
    ? m.sourceApp
    : origin === "clinicCreated"
      ? m.sourcePhone
      : origin === "walkIn"
        ? m.sourceWalkIn
        : null;
