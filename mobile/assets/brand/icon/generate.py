# Run: python3 assets/brand/icon/generate.py .   (from mobile/; needs rsvg-convert)
"""Saxlem app-icon variants, drawn from the mark's own geometry (512 grid)."""
import os, subprocess, sys
ROOT = sys.argv[1]
BIG, SMALL = 88, 48
TOP = (168, 80, 432, 256, BIG, SMALL, BIG, 0)      # x0 y0 x1 y1 tl tr br bl
BOT = (80, 256, 344, 432, BIG, 0, BIG, SMALL)
W, L = 9.5, 30  # plus half-width, half-length (centre 256,256)

def rrect(x0, y0, x1, y1, tl, tr, br, bl):
    p = [f"M{x0+tl},{y0}", f"L{x1-tr},{y0}"]
    if tr: p.append(f"A{tr},{tr} 0 0 1 {x1},{y0+tr}")
    p.append(f"L{x1},{y1-br}")
    if br: p.append(f"A{br},{br} 0 0 1 {x1-br},{y1}")
    p.append(f"L{x0+bl},{y1}")
    if bl: p.append(f"A{bl},{bl} 0 0 1 {x0},{y1-bl}")
    p.append(f"L{x0},{y0+tl}")
    if tl: p.append(f"A{tl},{tl} 0 0 1 {x0+tl},{y0}")
    return " ".join(p) + " Z"

def plus(cx=256, cy=256, w=W, l=L):
    pts = [
        f"M{cx-w},{cy-l}", f"A{w},{w} 0 0 1 {cx+w},{cy-l}", f"L{cx+w},{cy-w}",
        f"L{cx+l},{cy-w}", f"A{w},{w} 0 0 1 {cx+l},{cy+w}", f"L{cx+w},{cy+w}",
        f"L{cx+w},{cy+l}", f"A{w},{w} 0 0 1 {cx-w},{cy+l}", f"L{cx-w},{cy+w}",
        f"L{cx-l},{cy+w}", f"A{w},{w} 0 0 1 {cx-l},{cy-w}", f"L{cx-w},{cy-w}", "Z"]
    return " ".join(pts)

TOP_P, BOT_P, PLUS_P = rrect(*TOP), rrect(*BOT), plus()
CUT = f"{TOP_P} {BOT_P} {PLUS_P}"  # even-odd: plus becomes a hole

# The mark sits at 264..760 of 1024 on the current icon: 352 grid units -> 496px.
S = 496 / 352
T = 264 - 80 * S

def svg(bg, body, size=1024):
    return f'''<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" viewBox="0 0 1024 1024">
<defs>
 <linearGradient id="aura" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="#3B6BFF"/><stop offset="1" stop-color="#14B7D4"/></linearGradient>
 <linearGradient id="night" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="#141C3D"/><stop offset="1" stop-color="#070B1A"/></linearGradient>
 <radialGradient id="glow" cx=".5" cy=".42" r=".55"><stop offset="0" stop-color="#3B6BFF" stop-opacity=".38"/><stop offset="1" stop-color="#3B6BFF" stop-opacity="0"/></radialGradient>
 <linearGradient id="gTop" gradientUnits="userSpaceOnUse" x1="168" y1="80" x2="432" y2="256"><stop offset="0" stop-color="#5B85FF"/><stop offset="1" stop-color="#2148F0"/></linearGradient>
 <linearGradient id="gBot" gradientUnits="userSpaceOnUse" x1="80" y1="256" x2="344" y2="432"><stop offset="0" stop-color="#2FE0D9"/><stop offset="1" stop-color="#13B0EA"/></linearGradient>
</defs>
{bg}
<g transform="translate({T},{T}) scale({S})">{body}</g>
</svg>'''

variants = {
  # Light (default): white mark, plus cut through to the aura. Opaque, no alpha.
  "light": svg('<rect width="1024" height="1024" fill="url(#aura)"/>',
               f'<path fill="#FFFFFF" fill-rule="evenodd" d="{CUT}"/>'),
  # Dark: Design A night with a soft blue glow, full-colour mark, white plus.
  "dark": svg('<rect width="1024" height="1024" fill="url(#night)"/><rect width="1024" height="1024" fill="url(#glow)"/>',
              f'<path fill="url(#gTop)" d="{TOP_P}"/><path fill="url(#gBot)" d="{BOT_P}"/><path fill="#FFFFFF" d="{PLUS_P}"/>'),
  # Tinted (iOS): grayscale; the system tints by brightness.
  "tinted": svg('<rect width="1024" height="1024" fill="#000000"/>',
                f'<path fill="#FFFFFF" fill-rule="evenodd" d="{CUT}"/>'),
}
out = os.path.join(ROOT, "assets/brand/icon")
os.makedirs(out, exist_ok=True)
for name, s in variants.items():
    path = os.path.join(out, f"app_icon_{name}.svg")
    open(path, "w").write(s)
    png = os.path.join(out, f"app_icon_{name}.png")
    subprocess.run(["rsvg-convert", "-w", "1024", "-h", "1024", "-o", png, path], check=True)

# Icon Composer layers (iOS 26 Liquid Glass / clear): separate shapes on a
# transparent 1024 canvas, for a designer to drop into Icon Composer.
layers = os.path.join(out, "icon_composer_layers")
os.makedirs(layers, exist_ok=True)
open(os.path.join(layers, "1_top.svg"), "w").write(svg("", f'<path fill="url(#gTop)" d="{TOP_P}"/>'))
open(os.path.join(layers, "2_bottom.svg"), "w").write(svg("", f'<path fill="url(#gBot)" d="{BOT_P}"/>'))
open(os.path.join(layers, "3_plus.svg"), "w").write(svg("", f'<path fill="#FFFFFF" d="{PLUS_P}"/>'))

# Android adaptive icon (vector drawables, 108dp viewport, mark 50dp wide).
k = 50 / 352
off = (108 - 50) / 2 - 80 * k
def vec(body, gradient=False):
    ns = 'xmlns:android="http://schemas.android.com/apk/res/android"'
    if gradient: ns += ' xmlns:aapt="http://schemas.android.com/aapt"'
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by assets/brand/icon (Saxlem mark, 512 grid). Do not hand-edit. -->
<vector {ns}
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
{body}
</vector>
'''
grp = lambda inner: f'''    <group android:translateX="{off:.4f}" android:translateY="{off:.4f}"
        android:scaleX="{k:.6f}" android:scaleY="{k:.6f}">
{inner}
    </group>'''
res = os.path.join(ROOT, "android/app/src/main/res")
os.makedirs(os.path.join(res, "drawable"), exist_ok=True)
os.makedirs(os.path.join(res, "mipmap-anydpi-v26"), exist_ok=True)
open(os.path.join(res, "drawable/ic_launcher_foreground.xml"), "w").write(vec(grp(
    f'        <path android:fillColor="#FFFFFFFF" android:fillType="evenOdd"\n            android:pathData="{CUT}" />')))
open(os.path.join(res, "drawable/ic_launcher_monochrome.xml"), "w").write(vec(grp(
    f'        <path android:fillColor="#FFFFFFFF" android:fillType="evenOdd"\n            android:pathData="{CUT}" />')))
open(os.path.join(res, "drawable/ic_launcher_background.xml"), "w").write(vec(
'''    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient android:type="linear"
                android:startX="0" android:startY="0" android:endX="108" android:endY="108">
                <item android:offset="0" android:color="#FF3B6BFF" />
                <item android:offset="1" android:color="#FF14B7D4" />
            </gradient>
        </aapt:attr>
    </path>''', gradient=True))
adaptive = '''<?xml version="1.0" encoding="utf-8"?>
<!-- Android 8+: layered icon. The monochrome layer is what Android 13+ uses for
     themed icons (and Android 16 QPR2 auto-theming), so the mark stays ours. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
'''
open(os.path.join(res, "mipmap-anydpi-v26/ic_launcher.xml"), "w").write(adaptive)
print("ok", off, k)
